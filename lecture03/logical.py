x = 10
y = 20
z = 30

# Using 'and' operator
if x < y and y < z:
    print("x is less than y and y is less than z.")

# Using 'or' operator    
if x < y and y > z:
    print("x is less than y and y is greater than z.")

# Using 'not' operator    
if not (x > y):
    print("x is not greater than y.")
